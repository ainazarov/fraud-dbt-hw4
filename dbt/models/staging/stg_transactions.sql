with normalized as (
    select
        trimBoth(toString(src.transaction_id)) as transaction_id,
        trimBoth(toString(src.dataset)) as dataset,
        toUInt64(src.row_number) as row_number,
        toDateTime(src.transaction_time, 'UTC') as transaction_time,
        coalesce(nullIf(lowerUTF8(trimBoth(src.merch)), ''), 'unknown') as merchant,
        coalesce(nullIf(lowerUTF8(trimBoth(src.cat_id)), ''), 'unknown') as category,
        toDecimal64(src.amount, 2) as amount,
        lowerUTF8(trimBoth(src.name_1)) as first_name,
        lowerUTF8(trimBoth(src.name_2)) as last_name,
        upperUTF8(trimBoth(src.gender)) as gender,
        lowerUTF8(trimBoth(src.street)) as street,
        lowerUTF8(trimBoth(src.one_city)) as city,
        upperUTF8(trimBoth(src.us_state)) as state,
        trimBoth(toString(src.post_code)) as postal_code,
        toFloat64(src.lat) as lat,
        toFloat64(src.lon) as lon,
        toUInt32(src.population_city) as city_population,
        lowerUTF8(trimBoth(src.jobs)) as job,
        toFloat64(src.merchant_lat) as merchant_lat,
        toFloat64(src.merchant_lon) as merchant_lon,
        toUInt8(src.target) as is_fraud
    from {{ source('transactions_db', 'transactions') }} as src
)

select
    transaction_id,
    dataset,
    row_number,
    transaction_time,
    toDate(transaction_time, 'UTC') as transaction_date,
    {{ dbt_date.day_of_week('transaction_time', isoweek=true) }} as weekday_iso,
    toHour(transaction_time, 'UTC') as transaction_hour,
    merchant,
    category,
    amount,
    {{ customer_key(['first_name', 'last_name', 'street', 'postal_code']) }} as customer_id,
    first_name,
    last_name,
    gender,
    street,
    city,
    state,
    postal_code,
    lat,
    lon,
    city_population,
    job,
    merchant_lat,
    merchant_lon,
    is_fraud,
    {{ amount_bucket('amount') }} as amount_bucket
from normalized
